/** 翻译：缺 key 时回退简体，再回退 key 本身 */
export function t(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const s = DICTS[lang]?.[key] ?? zhCN[key] ?? key
  if (!vars) return s
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`))
}

