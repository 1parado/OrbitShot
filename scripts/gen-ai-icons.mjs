// Generate src/shared/ai-icons.ts — embed AI logos as data URLs
import fs from 'fs'

const ICON_DIR = 'icon'
const OUT = 'src/shared/ai-icons.ts'

// site id -> source file
const MAP = {
  chatgpt: 'chatgpt.svg',
  claude: 'claude.svg',
  gemini: 'gemini.svg',
  deepseek: 'deepseek.svg',
  doubao: 'doubao.svg',
  kimi: 'kimi.svg',
  qwen: 'qwen.png',
  grok: 'grok-(xai).svg',
  perplexity: 'perplexity.svg',
  copilot: 'microsoft-copilot.svg',
  mistral: 'mistral-ai.svg',
  poe: 'poe.svg',
  character: 'character.ai.svg',
}

const entries = []
for (const [id, file] of Object.entries(MAP)) {
  const p = `${ICON_DIR}/${file}`
  if (!fs.existsSync(p)) {
    console.warn(`WARN missing: ${p}`)
    continue
  }
  const mime = file.endsWith('.png') ? 'image/png' : 'image/svg+xml'
  const b64 = fs.readFileSync(p).toString('base64')
  entries.push(`  ${JSON.stringify(id)}: 'data:${mime};base64,${b64}',`)
  console.log(`${id} <- ${file} (${b64.length} b64 chars)`)
}

const ts = `// Auto-generated by scripts/gen-ai-icons.mjs — AI logo data URLs
export const AI_ICONS: Record<string, string> = {
${entries.join('\n')}
}
`
fs.writeFileSync(OUT, ts)
console.log(`\nwritten: ${OUT}`)
